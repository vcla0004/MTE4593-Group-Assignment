# Rubric coverage: R2.1, R2.3, R2.7, R4.3, RB.6, RB.5
"""Carbon displaced by one BWRX-300: Darlington (Ontario) vs Liddell (NSW, NEM).

Reads 03_LCA_Calculations/parameters_run1.yaml only. Writes results/displacement.md.
Run:  python3 -I 03_LCA_Calculations/scripts/displacement.py

Method (full working is printed into the results file):
  annual output E  [kWh/yr] = net_MWe * 1000 * 8760 * CF
  avoided in year y [t/yr]  = E * (EF_grid(y) - EF_smr) / 1e6     (g -> t)
  cumulative to year Y      = sum over operating years y = start .. min(Y, start + life - 1)
EF_grid(y) is either a static factor or a trajectory (linear between stated anchor points, flat after).
Signs are kept: if EF_grid < EF_smr the "avoided" value goes negative.
"""
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]
P = yaml.safe_load((ROOT / "parameters_run1.yaml").read_text())["parameters"]
OUT = ROOT / "results" / "displacement.md"


def v(name, key="value"):
    return float(P[name][key])


def lin(y, y0, e0, y1, e1):
    """Linear from (y0,e0) to (y1,e1); flat outside."""
    if y <= y0:
        return e0
    if y >= y1:
        return e1
    return e0 + (e1 - e0) * (y - y0) / (y1 - y0)


def annual_kwh(p):
    return p["net_mwe"] * 1000 * 8760 * p["cf"]


def base():
    return {
        "net_mwe": v("net_mwe"), "cf": v("capacity_factor"), "life": int(v("design_life_yr")),
        "smr": v("smr_lca_g_per_kwh"),
        "ont_avg": v("ont_avg_2024_taf"), "ont_2040": v("ont_future_2040"), "ont_y0": int(v("ont_traj_start_year")),
        "ont_marg": v("ont_marginal_taf"), "ont_marg_conv": int(v("ont_marginal_converge_year")),
        "nsw": v("nsw_scope2_2025"), "nem_y0": int(v("nem_traj_start_year")),
        "exit_t1": int(v("nem_coal_exit_year_stepchange")), "exit_t2": int(v("nem_slow_exit_year")),
        "floor": v("nem_floor_g_per_kwh"),
        "bays": v("bayswater_ei"), "coal_lca": v("coal_lca_unece"),
    }


def trajectories(p):
    return {
        "ON-avg-traj": lambda y: lin(y, p["ont_y0"], p["ont_avg"], 2040, p["ont_2040"]),
        "ON-avg-flat": lambda y: p["ont_avg"],
        "ON-marginal-flat": lambda y: p["ont_marg"],
        "ON-marginal-declining": lambda y: lin(y, p["ont_y0"], p["ont_marg"], p["ont_marg_conv"], p["ont_2040"]),
        "NEM-T0-frozen": lambda y: p["nsw"],
        "NEM-T1-StepChange-proxy": lambda y: lin(y, p["nem_y0"], p["nsw"], p["exit_t1"], p["floor"]),
        "NEM-T2-slow": lambda y: lin(y, p["nem_y0"], p["nsw"], p["exit_t2"], p["floor"]),
        "UB-Bayswater-flat": lambda y: p["bays"],
        "UB-coal-LCA-flat": lambda y: p["coal_lca"],
    }


def cumulative(p, ef, start, to_year=None, units=1):
    """t CO2e avoided from start to to_year inclusive (None = whole design life)."""
    end = start + p["life"] - 1
    if to_year is not None:
        end = min(end, to_year)
    E = annual_kwh(p)
    return units * sum(E * (ef(y) - p["smr"]) / 1e6 for y in range(start, end + 1)) if end >= start else 0.0


def fmt_t(t):
    if abs(t) >= 1e6:
        return f"{t/1e6:,.2f} Mt"
    return f"{t/1e3:,.0f} kt"


def main():
    p = base()
    T = trajectories(p)
    E = annual_kwh(p)
    L = []
    w = L.append
    w("Rubric coverage: R2.1, R2.3, R2.7, R4.3, RB.6, RB.5\n")
    w("# Displacement: CO2e avoided by one BWRX-300, Darlington vs Liddell\n")
    w("Generated by `03_LCA_Calculations/scripts/displacement.py` from `parameters_run1.yaml`. Do not edit by hand; change the YAML and re-run.\n")
    w("**Status: PROVISIONAL.** Every grid factor, cost and date below is `TO VERIFY` (primary sources could not be opened on 20/10/2026: proxy policy block) or an analyst assumption/placeholder; see the `status` field of each parameter. The SMR life-cycle value is our own LCA result (results/lca.md section 0: median 4.2, P5-P95 3.0-5.8 g CO2e/kWh; re-based 21/10, job Q2), whose inputs are themselves TO VERIFY.\n")

    # ---- Working ----
    w("## 1. Working\n")
    w(f"- Annual output, one unit: E = {p['net_mwe']:.0f} MWe x 1,000 kW/MW x 8,760 h x {p['cf']:.2f} = **{E/1e9:.3f} TWh/yr** ({E:,.0f} kWh/yr)")
    w(f"- SMR life-cycle intensity (our LCA, Monte Carlo median): {p['smr']} g CO2e/kWh (P5–P95 {v('smr_lca_g_per_kwh','low')}–{v('smr_lca_g_per_kwh','high')}). Former placeholder: UNECE (2021) midpoint {v('smr_lca_unece_g_per_kwh')} ({v('smr_lca_unece_g_per_kwh','low')}–{v('smr_lca_unece_g_per_kwh','high')})")
    w(f"- Avoided per year = E x (EF_grid - EF_smr) / 10^6 t. Example, NSW 2025: {E:,.0f} x ({p['nsw']:.0f} - {p['smr']}) / 10^6 = {E*(p['nsw']-p['smr'])/1e6:,.0f} t/yr")
    w(f"- Design life {p['life']} years; cumulative sums run from the first full year of operation.")
    w("- Trajectories (analyst constructions from the anchor points in the YAML; not AEMO or IESO series):")
    w(f"  - ON-avg-traj: {p['ont_avg']} g/kWh in {p['ont_y0']} (TAF 2024 average), linear to {p['ont_2040']} in 2040 (IESO 2024 outlook lead), flat after")
    w(f"  - ON-marginal-flat: {p['ont_marg']} g/kWh held flat (TAF marginal lead; an upper bound for the lifetime, because gas will not stay on the margin for 60 years)")
    w(f"  - ON-marginal-declining: {p['ont_marg']} g/kWh in {p['ont_y0']}, linear to {p['ont_2040']} by {p['ont_marg_conv']} (assumption: gas leaves the margin), flat after")
    w(f"  - NEM-T0-frozen: {p['nsw']} g/kWh held flat (no further decarbonisation; upper bound for the grid average)")
    w(f"  - NEM-T1-StepChange-proxy: {p['nsw']} in {p['nem_y0']}, linear to a floor of {p['floor']} g/kWh in {p['exit_t1']} (2024 ISP Step Change coal exit lead), flat after")
    w(f"  - NEM-T2-slow: as T1 but reaching the floor in {p['exit_t2']}")
    w(f"  - UB-Bayswater-flat: {p['bays']} g/kWh sent out (coal unit next to Liddell; Liddell itself closed April 2023). UB-coal-LCA-flat: {p['coal_lca']} g/kWh life cycle (UNECE coal) for a boundary-consistent comparison")
    w("")

    # ---- Table 1: static first-year ----
    w("## 2. Annual CO2e avoided at static grid factors (one unit)\n")
    w("| Displaced electricity | EF (g/kWh) | Source key / status | Avoided (t/yr) | Ratio to Ontario avg 2024 |")
    w("|---|---|---|---|---|")
    ref = E * (p["ont_avg"] - p["smr"]) / 1e6
    rows = [
        ("Ontario average 2022 (CER)", v("ont_avg_2022_cer"), "cer_ontario_profile, TO VERIFY"),
        ("Ontario average 2023 (energy snapshot; deck value)", v("ont_avg_2023_snapshot"), "ontario_energy_snapshot, TO VERIFY"),
        ("Ontario average 2024 (TAF)", p["ont_avg"], "taf2025, TO VERIFY"),
        ("Ontario marginal (TAF 2024 MEF lead)", p["ont_marg"], "taf2025, TO VERIFY"),
        ("Ontario gas-fired generation (TAF 2021)", v("ont_marginal_taf", "high"), "taf2021, TO VERIFY"),
        ("NSW/NEM average 2025 (NGA Factors scope 2)", p["nsw"], "dcceew2025_ngaf, TO VERIFY"),
        ("Bayswater coal, sent out (AEMO CDEII lead)", p["bays"], "aemo_cdeii, TO VERIFY"),
        ("Coal, life cycle (UNECE central)", p["coal_lca"], "unece2021, TO VERIFY"),
        ("Gas combined cycle, life cycle (UNECE midpoint)", v("gas_cc_lca_unece"), "unece2021, TO VERIFY"),
    ]
    for name, ef, src in rows:
        a = E * (ef - p["smr"]) / 1e6
        w(f"| {name} | {ef:,.0f} | {src} | {a:,.0f} | {a/ref:,.1f}x |")
    w("")
    nsw_a = E * (p["nsw"] - p["smr"]) / 1e6
    deck_ont = E * (v("ont_avg_2023_snapshot") - p["smr"]) / 1e6
    w("**Check of the deck (slide 'location'):** "
      f"2.37 TWh/yr is right ({E/1e9:.3f}). NSW {nsw_a/1e6:.2f} Mt/yr matches the deck's 1.5 Mt. "
      f"Ontario at 53 g/kWh gives {deck_ont/1e6:.3f} Mt/yr, matching the deck's 0.11 Mt, so the deck's 13x ({nsw_a/deck_ont:.1f}x) is arithmetically right "
      f"for those inputs. But the latest Ontario average (TAF 2024, {p['ont_avg']} g/kWh) gives {ref/1e6:.2f} Mt/yr and a ratio of {nsw_a/ref:.1f}x, "
      f"and Ontario's marginal factor ({p['ont_marg']:.0f} g/kWh) gives {E*(p['ont_marg']-p['smr'])/1e6/1e6:.2f} Mt/yr and a ratio of only "
      f"{nsw_a/(E*(p['ont_marg']-p['smr'])/1e6):.1f}x. The deck compares today's NSW grid with an SMR that could not run in NSW before about 2040; see section 3.\n")

    # ---- Table 2: cumulative ----
    w("## 3. Cumulative CO2e avoided, one unit, by start year and grid trajectory\n")
    w("| Site | Start | Grid case | Year-1 EF (g/kWh) | To 2035 | To 2050 | Whole life |")
    w("|---|---|---|---|---|---|---|")
    cases = [
        ("Darlington U1", int(v("ont_unit1_start")), "ON-avg-traj"),
        ("Darlington U1", int(v("ont_unit1_start")), "ON-avg-flat"),
        ("Darlington U1", int(v("ont_unit1_start")), "ON-marginal-declining"),
        ("Darlington U1", int(v("ont_unit1_start")), "ON-marginal-flat"),
    ]
    for s in (int(v("aus_start_coalition")), int(v("aus_start_csiro")), int(v("aus_start_late"))):
        for t in ("NEM-T0-frozen", "NEM-T1-StepChange-proxy", "NEM-T2-slow"):
            cases.append(("Liddell", s, t))
    cases += [("Liddell", int(v("aus_start_csiro")), "UB-Bayswater-flat"), ("Liddell", int(v("aus_start_csiro")), "UB-coal-LCA-flat")]
    results = {}
    for site, s, t in cases:
        ef = T[t]
        c35, c50, cl = cumulative(p, ef, s, 2035), cumulative(p, ef, s, 2050), cumulative(p, ef, s)
        results[(site, s, t)] = (c35, c50, cl)
        w(f"| {site} | {s} | {t} | {ef(s):,.0f} | {fmt_t(c35)} | {fmt_t(c50)} | {fmt_t(cl)} |")
    w("")
    w("Note: the Bayswater and coal-LCA rows hold coal intensity flat for 60 years. They are upper bounds only: Bayswater itself is scheduled to close [TODO: verify AGL's closure date], and no NEM scenario keeps coal on the margin to 2100.\n")

    # ---- Four units at Darlington ----
    s1, s2 = int(v("ont_unit1_start")), int(v("ont_units2to4_start"))
    w("## 4. All four Darlington units (U1 from {}, U2–U4 from {})\n".format(s1, s2))
    w("| Grid case | To 2035 | To 2050 | Whole life (all units) |")
    w("|---|---|---|---|")
    for t in ("ON-avg-traj", "ON-avg-flat", "ON-marginal-declining", "ON-marginal-flat"):
        ef = T[t]
        r = [cumulative(p, ef, s1, Y) + cumulative(p, ef, s2, Y, units=3) for Y in (2035, 2050, None)]
        w(f"| {t} | {fmt_t(r[0])} | {fmt_t(r[1])} | {fmt_t(r[2])} |")
    w("")

    # ---- Sensitivity ----
    w("## 5. Sensitivity (one at a time), Liddell central case: start {}, NEM-T1, to 2050 and whole life\n".format(int(v("aus_start_csiro"))))
    s0 = int(v("aus_start_csiro"))

    def run(mod, start=s0, traj="NEM-T1-StepChange-proxy"):
        q = dict(p)
        q.update(mod)
        TT = trajectories(q)
        return cumulative(q, TT[traj], start, 2050), cumulative(q, TT[traj], start)

    c50_0, cl_0 = run({})
    sens = [
        ("Capacity factor", {"cf": v("capacity_factor", "low")}, {"cf": v("capacity_factor", "high")}, f"{v('capacity_factor','low')}–{v('capacity_factor','high')}"),
        ("Net output (MWe)", {"net_mwe": v("net_mwe", "low")}, {"net_mwe": v("net_mwe", "high")}, f"{v('net_mwe','low'):.0f}–{v('net_mwe','high'):.0f}"),
        ("SMR life cycle (our MC P95–P5)", {"smr": v("smr_lca_g_per_kwh", "high")}, {"smr": v("smr_lca_g_per_kwh", "low")}, f"{v('smr_lca_g_per_kwh','high')}–{v('smr_lca_g_per_kwh','low')} g/kWh"),
        ("SMR life cycle, UNECE midpoint instead of ours", {"smr": v("smr_lca_unece_g_per_kwh")}, {"smr": v("smr_lca_g_per_kwh")}, f"{v('smr_lca_unece_g_per_kwh')} vs {v('smr_lca_g_per_kwh')} g/kWh"),
        ("SMR life cycle stress (IPCC lead)", {"smr": v("smr_lca_stress_g_per_kwh", "high")}, {"smr": v("smr_lca_stress_g_per_kwh", "value")}, "110–12 g/kWh"),
        ("NEM floor after coal exit", {"floor": v("nem_floor_g_per_kwh", "low")}, {"floor": v("nem_floor_g_per_kwh", "high")}, "0–80 g/kWh"),
        ("Coal exit year (T1)", {"exit_t1": 2035}, {"exit_t1": 2045}, "2035–2045"),
        ("Design life", {"life": int(v("design_life_yr", "low"))}, {"life": int(v("design_life_yr", "high"))}, "40–80 yr"),
    ]
    w(f"Central: to 2050 = {fmt_t(c50_0)}; whole life = {fmt_t(cl_0)}.\n")
    w("| Parameter | Range | To 2050 (low → high input) | Whole life (low → high input) |")
    w("|---|---|---|---|")
    for name, lo, hi, rng in sens:
        a, b = run(lo), run(hi)
        w(f"| {name} | {rng} | {fmt_t(a[0])} → {fmt_t(b[0])} | {fmt_t(a[1])} → {fmt_t(b[1])} |")
    # start year / trajectory are scenario choices, show separately
    w(f"| Start year | 2035–2045 | {fmt_t(run({}, 2035)[0])} → {fmt_t(run({}, 2045)[0])} | {fmt_t(run({}, 2035)[1])} → {fmt_t(run({}, 2045)[1])} |")
    w(f"| Grid trajectory | T1 → T0 frozen | {fmt_t(c50_0)} → {fmt_t(run({}, s0, 'NEM-T0-frozen')[0])} | {fmt_t(cl_0)} → {fmt_t(run({}, s0, 'NEM-T0-frozen')[1])} |")
    w("")
    w("Reading: the grid trajectory and the start year move the result by an order of magnitude, and under T1 so does the post-coal floor (the SMR spends its whole life displacing that residual mix, so the floor is effectively the displaced intensity). Capacity factor, net output and the SMR's own life-cycle value (our 90% interval, or swapping in the UNECE midpoint) move it by a few per cent. The SMR's life-cycle number matters only in the stress case (110 g/kWh) and on a decarbonised grid, where it can turn the result negative.\n")

    # ---- Boundary note ----
    w("## 6. Method caveats (for §7 and the uncertainty discussion)\n")
    w("1. **Boundary mismatch.** Grid factors (NGA scope 2, TAF, CER) count combustion at the power station only; the SMR value is life cycle. Comparing them understates displacement slightly. The boundary-consistent row (UNECE coal LCA vs SMR LCA) is given as the upper bound.")
    w("2. **Average vs marginal.** A new 300 MWe baseload unit displaces whatever is on the margin when it runs, not the average. In Ontario the margin is mostly gas, so the marginal factor is the better short-run estimate; over a 60-year life the margin decarbonises, so the flat marginal case is an upper bound.")
    w("3. **Counterfactual.** In both grids the alternative to an SMR is not 'today's grid forever' but other new supply. The same-money comparison (`same_money.md`) addresses this.")
    w("4. **Liddell closed in April 2023.** An SMR at the Liddell site would reuse the site and grid connection but displaces the NEM mix, not Liddell. Bayswater intensity is therefore an upper bound only.")
    w("5. **Placeholders.** The SMR life-cycle value is now ours (4.2 g/kWh, 21/10). Net output, capacity factor, design life and start dates are still placeholders for Leroy's sourced data (plan §5); re-run when they are entered in the YAML.\n")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
