# Rubric coverage: R2.3, R2.6, R2.7, R3.1, R4.3, R3.7, RB.5
"""Carbon value of schedule: CO2e lost per month / year of delay, Darlington vs Liddell.

Reads 03_LCA_Calculations/parameters_run1.yaml only. Writes results/schedule_value.md.
Run:  python3 -I 03_LCA_Calculations/scripts/schedule_value.py

Method:
  monthly output M [kWh] = E / 12, with E = net_MWe * 1000 * 8760 * CF
  gross loss per month of delay = M * (EF_grid(start) - EF_smr) / 1e6           [t]
      (the displacement that does not happen in the first month)
  net loss per month of delay   = M * (EF_grid(start) - EF_grid(end_of_life+1)) / 1e6
      (a delayed plant still runs its full design life, so the lost first month is
       partly recovered as an extra month at the end, on a cleaner grid)
  break-even delay for an embodied saving S [t] = S / (net loss per day)
  cost of a k-year delay to 2050 = cumulative(start) - cumulative(start + k), both to 2050
  C1 break-even (Q2, 21/10): days = C1 saving [t] / loss per day [t/day] of the delayed unit(s)
  C1 carbon value = saving [t] x carbon price [C$/t]; set against one month's delay of Units 2-4:
      CO2e lost x the same price; deferred output x OPG LCOE; carrying cost = capital x r / 12
  Also reads parameters_run5.yaml (analyst run 5; read only, never edited) for the Units 2-4 capital,
  OPG's LCOE lead and the discount-rate set, so the dollar figures match results/initiative_cost.md.
"""
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]
P = yaml.safe_load((ROOT / "parameters_run1.yaml").read_text())["parameters"]
OUT = ROOT / "results" / "schedule_value.md"
R5_PATH = ROOT / "parameters_run5.yaml"
R5 = yaml.safe_load(R5_PATH.read_text())["parameters"] if R5_PATH.exists() else {}


def v(name, key="value"):
    return float(P[name][key])


def lin(y, y0, e0, y1, e1):
    if y <= y0:
        return e0
    if y >= y1:
        return e1
    return e0 + (e1 - e0) * (y - y0) / (y1 - y0)


net, cf, life, smr = v("net_mwe"), v("capacity_factor"), int(v("design_life_yr")), v("smr_lca_g_per_kwh")
E = net * 1000 * 8760 * cf
M = E / 12
D = E / 365

ont_y0, ont_avg, ont_2040 = int(v("ont_traj_start_year")), v("ont_avg_2024_taf"), v("ont_future_2040")
ont_m, ont_mc = v("ont_marginal_taf"), int(v("ont_marginal_converge_year"))
nsw, nem_y0, floor = v("nsw_scope2_2025"), int(v("nem_traj_start_year")), v("nem_floor_g_per_kwh")
x1, x2 = int(v("nem_coal_exit_year_stepchange")), int(v("nem_slow_exit_year"))

TR = {
    "ON-avg-traj": lambda y: lin(y, ont_y0, ont_avg, 2040, ont_2040),
    "ON-avg-flat": lambda y: ont_avg,
    "ON-marginal-declining": lambda y: lin(y, ont_y0, ont_m, ont_mc, ont_2040),
    "ON-marginal-flat": lambda y: ont_m,
    "NEM-T0-frozen": lambda y: nsw,
    "NEM-T1-StepChange-proxy": lambda y: lin(y, nem_y0, nsw, x1, floor),
    "NEM-T2-slow": lambda y: lin(y, nem_y0, nsw, x2, floor),
}


def cum(ef, start, to_year):
    end = min(start + life - 1, to_year)
    return sum(E * (ef(y) - smr) / 1e6 for y in range(start, end + 1)) if end >= start else 0.0


def main():
    L = []
    w = L.append
    w("Rubric coverage: R2.3, R2.6, R2.7, R3.1, R4.3, R3.7, RB.5\n")
    w("# Value of schedule: CO2e cost of delay, Darlington vs Liddell\n")
    w("Generated by `03_LCA_Calculations/scripts/schedule_value.py` from `parameters_run1.yaml`. **PROVISIONAL:** all inputs are TO VERIFY, assumptions or placeholders (see the YAML `status` fields).\n")
    w("## 1. Working\n")
    w(f"- Monthly output of one unit: M = {E:,.0f} kWh/yr / 12 = {M:,.0f} kWh (daily {D:,.0f} kWh)")
    w("- Gross loss per month of delay = M x (EF_grid(start) - EF_smr) / 10^6 t: the displacement that does not happen while the plant is late.")
    w("- Net loss per month = M x (EF_grid(start) - EF_grid(start + life)) / 10^6 t: a late plant still runs its full life, so the lost month comes back at the end of life, on a cleaner grid. Net is the honest figure for a long-lived plant; gross is the figure for 'emissions to 2050'.")
    w("- Break-even delay for an embodied-carbon saving S (t CO2e) = S / (loss per day), on both bases. Shown per 1 kt of saving so Sam's C1 result can be scaled directly. The gross basis matches carbon budgets to 2035/2050 (emissions now matter more than emissions in the 2090s); the net basis counts the whole operating life equally. A flat grid gives zero net loss by construction, which is an artefact of assuming the grid never changes.\n")

    w("## 2. CO2e lost per month of delay, one unit\n")
    w("| Site, start year | Grid case | EF at start (g/kWh) | EF at end of life | Gross t/month | Net t/month | Net t/day | Days to cancel 1 kt (gross, to-2050 view) | Days to cancel 1 kt (net, whole-life view) |")
    w("|---|---|---|---|---|---|---|---|---|")
    cases = [(f"Darlington U1, {int(v('ont_unit1_start'))}", int(v("ont_unit1_start")), t) for t in ("ON-avg-traj", "ON-avg-flat", "ON-marginal-declining", "ON-marginal-flat")]
    cases += [(f"Darlington U2–U4 (each), {int(v('ont_units2to4_start'))}", int(v("ont_units2to4_start")), t) for t in ("ON-avg-traj", "ON-marginal-declining", "ON-marginal-flat")]
    cases += [(f"Liddell, {s}", s, t) for s in (int(v("aus_start_coalition")), int(v("aus_start_csiro"))) for t in ("NEM-T0-frozen", "NEM-T1-StepChange-proxy", "NEM-T2-slow")]
    rows = {}
    for label, s, t in cases:
        ef = TR[t]
        g = M * (ef(s) - smr) / 1e6
        n = M * (ef(s) - ef(s + life)) / 1e6
        nd = n * 12 / 365
        be = (1000 / nd) if nd > 0 else float("inf")
        rows[(label, t)] = (g, n, be)
        be_s = f"{be:,.1f}" if be != float("inf") else "none (flat grid: the month is recovered at end of life)"
        bg = 1000 / (g * 12 / 365) if g > 0 else float("inf")
        bg_s = f"{bg:,.1f}" if bg != float("inf") else "n/a"
        w(f"| {label} | {t} | {ef(s):,.0f} | {ef(s+life):,.0f} | {g:,.0f} | {n:,.0f} | {nd:,.0f} | {bg_s} | {be_s} |")
    w("")

    # Units 2-4 programme
    w("## 3. A one-month slip of the whole Units 2–4 programme (three units)\n")
    s2 = int(v("ont_units2to4_start"))
    w("| Grid case | Gross t/month | Net t/month |")
    w("|---|---|---|")
    for t in ("ON-avg-traj", "ON-marginal-declining", "ON-marginal-flat"):
        ef = TR[t]
        w(f"| {t} | {3*M*(ef(s2)-smr)/1e6:,.0f} | {3*M*(ef(s2)-ef(s2+life))/1e6:,.0f} |")
    w("")

    # Year-scale delay: Australian legal/licensing slip, and Darlington slip
    w("## 4. Cost of whole-year delays, CO2e avoided to 2050 (one unit)\n")
    w("Shows the climate cost of each year it takes to change the law, license and build in Australia, compared with a slip at Darlington.\n")
    w("| Site | Grid case | Start A | Start B | Avoided to 2050, start A | start B | Lost to 2050 | Lost per year of delay |")
    w("|---|---|---|---|---|---|---|---|")
    yr_cases = [
        ("Liddell", "NEM-T0-frozen", int(v("aus_start_coalition")), int(v("aus_start_csiro"))),
        ("Liddell", "NEM-T1-StepChange-proxy", int(v("aus_start_coalition")), int(v("aus_start_csiro"))),
        ("Liddell", "NEM-T2-slow", int(v("aus_start_coalition")), int(v("aus_start_csiro"))),
        ("Liddell", "NEM-T2-slow", int(v("aus_start_csiro")), int(v("aus_start_late"))),
        ("Darlington U1", "ON-avg-traj", int(v("ont_unit1_start")), int(v("ont_unit1_start")) + 2),
        ("Darlington U1", "ON-marginal-declining", int(v("ont_unit1_start")), int(v("ont_unit1_start")) + 2),
    ]
    for site, t, a, b in yr_cases:
        ca, cb = cum(TR[t], a, 2050), cum(TR[t], b, 2050)
        w(f"| {site} | {t} | {a} | {b} | {ca/1e6:,.2f} Mt | {cb/1e6:,.2f} Mt | {(ca-cb)/1e6:,.2f} Mt | {(ca-cb)/(b-a)/1e6:,.2f} Mt/yr |")
    w("")

    # Sensitivity on the key break-even
    w("## 5. Sensitivity of the Darlington U2–U4 break-even (net t/day; days per 1 kt saved), ON-marginal-declining\n")
    w("| Change | Net t/day | Days per 1 kt |")
    w("|---|---|---|")

    def be_for(cf_=cf, smr_=smr, m=ont_m, conv=ont_mc):
        ef = lambda y: lin(y, ont_y0, m, conv, ont_2040)
        Mx = net * 1000 * 8760 * cf_ / 12
        nd = Mx * (ef(s2) - ef(s2 + life)) / 1e6 * 12 / 365
        return nd, 1000 / nd

    for label, kw in [("Central", {}), ("CF 0.80", {"cf_": v("capacity_factor", "low")}), ("CF 0.95", {"cf_": v("capacity_factor", "high")}),
                      ("Marginal 472 (gas generation factor)", {"m": v("ont_marginal_taf", "high")}),
                      ("Gas leaves margin by 2040", {"conv": int(v("ont_marginal_converge_year", "low"))}),
                      ("Gas leaves margin by 2060", {"conv": int(v("ont_marginal_converge_year", "high"))})]:
        nd, d = be_for(**kw)
        w(f"| {label} | {nd:,.0f} | {d:,.1f} |")
    w("")
    # ---------------- Q2: C1 break-even table ----------------
    S1, S1lo, S1hi = v("c1_saving_t_per_unit"), v("c1_saving_t_per_unit", "low"), v("c1_saving_t_per_unit", "high")
    S3, S3lo, S3hi = v("c1_saving_t_units_2_4"), v("c1_saving_t_units_2_4", "low"), v("c1_saving_t_units_2_4", "high")
    w("## 6. Break-even delay for initiative C1 (LC3 in the Units 2–4 target structures)\n")
    w(f"C1 saves {S1:,.0f} t CO2e per unit (MC P5–P95 {S1lo:,.0f}–{S1hi:,.0f}) and {S3:,.0f} t for Units 2–4 ({S3lo:,.0f}–{S3hi:,.0f}) (`lca_scenarios.csv`, `lca_montecarlo_summary.csv`). "
      f"Break-even days = saving / CO2e lost per day of delay. Units 2–4 start {s2}. Two ways a delay can fall:\n")
    w("- **(a) Per unit:** one unit's saving against a delay to that unit (the same answer as all three units' saving against a three-unit slip, because both scale by 3).")
    w("- **(b) Programme saving, one unit late:** all of Units 2–4's saving against a delay to just one unit (e.g. the first LC3 pour holds one unit's critical path).")
    w("- Gross = to-2050 view (the displacement lost now); net = whole-life view (the month returns at end of life on a cleaner grid). Ranges use the C1 saving's P5–P95 only.\n")
    w("| Grid case (factor type) | Gross t/day per unit | Net t/day per unit | (a) gross days | (a) net days | (b) gross days | (b) net days |")
    w("|---|---|---|---|---|---|---|")
    be_rows = {}
    for t, lab in [("ON-avg-traj", "average, declining to 2040"), ("ON-avg-flat", "average, held at 2024"),
                   ("ON-marginal-declining", "marginal, gas leaves margin by 2050"), ("ON-marginal-flat", "marginal, held at 2024")]:
        ef = TR[t]
        g = D * (ef(s2) - smr) / 1e6
        n = D * (ef(s2) - ef(s2 + life)) / 1e6

        def rng(Sc, Sl, Sh, per):
            if per <= 0:
                return "none (flat grid)"
            return f"{Sc/per:,.1f} ({Sl/per:,.1f}–{Sh/per:,.1f})"
        be_rows[t] = (g, n)
        w(f"| {t} ({lab}) | {g:,.0f} | {n:,.0f} | {rng(S1,S1lo,S1hi,g)} | {rng(S1,S1lo,S1hi,n)} | {rng(S3,S3lo,S3hi,g)} | {rng(S3,S3lo,S3hi,n)} |")
    w("")
    ga, na = be_rows["ON-avg-traj"]
    gm, nm = be_rows["ON-marginal-declining"]
    w(f"Reading: on Ontario's **average** factor, C1's per-unit saving is cancelled by **{S1/ga:,.1f}–{S1/na:,.1f} days** (rounded {S1/ga:,.0f}–{S1/na:,.0f}) of delay to that unit (gross–net); "
      f"on the **marginal** factor (gas on the margin) by about **{S1/gm:,.1f}–{S1/nm:,.1f} days**. Even the whole Units 2–4 saving ({S3/1e3:,.1f} kt) is cancelled by "
      f"{S3/ga:,.0f}–{S3/na:,.0f} days (average) or {S3/gm:,.1f}–{S3/nm:,.1f} days (marginal) of delay to a single unit. "
      "C1 is therefore climate-positive only if it is schedule-neutral (plan §2.4).\n")

    # ---------------- Q2: carbon value vs one month's delay ----------------
    w("## 7. C1's carbon value against one month's delay to Units 2–4 (C$)\n")
    p26, p26_old = v("carbon_price_2026_cad"), v("carbon_price_2026_cad", "high")
    p30, p30_old = v("carbon_price_2030_cad"), v("carbon_price_2030_cad", "high")
    w(f"Carbon prices (all **TO VERIFY**): C${p26:.0f}/t in 2026 and C${p30:.0f}/t in 2030 on the federal headline industrial trajectory published 19 May 2026 (lead); "
      f"C${p26_old:.0f} and C${p30_old:.0f} on the superseded 2021 benchmark path that run 5 uses. C1's concrete would be placed about 2029–2033, so the 2030 price is the relevant one; 2026 is today's price.\n")
    w("| Carbon price (C$/t) | Basis | C1 carbon value, Units 2–4 (C$ m, P5–P95) | Value of the CO2e lost in a one-month Units 2–4 slip, average factor (gross / net, C$ m) | Same, marginal factor (gross / net, C$ m) |")
    w("|---|---|---|---|---|")
    month_t = {k: (3 * g * 365 / 12, 3 * n * 365 / 12) for k, (g, n) in be_rows.items()}
    for pr, basis in [(p26, "2026, new trajectory (lead)"), (p26_old, "2026, superseded path (run 5)"),
                      (p30, "2030, new trajectory (lead)"), (p30_old, "2030, superseded path (run 5)")]:
        cv = S3 * pr / 1e6
        ma, mm = month_t["ON-avg-traj"], month_t["ON-marginal-declining"]
        w(f"| {pr:.0f} | {basis} | {cv:,.2f} ({S3lo*pr/1e6:,.2f}–{S3hi*pr/1e6:,.2f}) | {ma[0]*pr/1e6:,.2f} / {ma[1]*pr/1e6:,.2f} | {mm[0]*pr/1e6:,.2f} / {mm[1]*pr/1e6:,.2f} |")
    w("")
    w(f"CO2e lost in a one-month slip of all three units: {month_t['ON-avg-traj'][0]:,.0f} t gross / {month_t['ON-avg-traj'][1]:,.0f} t net (average), "
      f"{month_t['ON-marginal-declining'][0]:,.0f} / {month_t['ON-marginal-declining'][1]:,.0f} t (marginal), against C1's {S3:,.0f} t.\n")

    # dollar cost of the month (run 5 inputs, read only)
    if R5:
        cap = float(R5["dnnp_u24_capital_cad"]["value"])
        luec = float(R5["opg_dnnp_lcoe_cad"]["value"])
        rates = [float(x) for x in R5["discount_rates"]["value"]]
        mwh_month = 3 * net * 8760 * cf / 12
        deferred = mwh_month * luec
        w("Direct cost of the same one-month slip (inputs from `parameters_run5.yaml`, read only; all TO VERIFY or assumptions):\n")
        w("| Cost item | Working | C$ m per month |")
        w("|---|---|---|")
        w(f"| Deferred output, valued at OPG's LCOE lead | 3 × {net:.0f} MW × 8,760 h × {cf:.2f} / 12 = {mwh_month:,.0f} MWh × C${luec:.0f}/MWh | {deferred/1e6:,.0f} |")
        for r in rates:
            w(f"| Carrying cost, upper bound (all Units 2–4 capital spent), r = {r:.0%} | C${cap/1e9:.1f} bn × {r:.0%} / 12 | {cap*r/12/1e6:,.0f} |")
        w("")
        cv_hi = S3hi * p30_old / 1e6
        w(f"Reading: the largest carbon value we can construct for C1 (P95 saving × C${p30_old:.0f}/t) is **C${cv_hi:,.2f} m**. One month's slip of Units 2–4 costs "
          f"**C${cap*rates[0]/12/1e6:,.0f}–{cap*rates[-1]/12/1e6:,.0f} m** in carrying cost alone, and defers about **C${deferred/1e6:,.0f} m** of output, i.e. "
          f"**{cap*rates[0]/12/1e6/cv_hi:,.0f}–{max(deferred, cap*rates[-1]/12)/1e6/(S3*p26/1e6):,.0f} times** C1's carbon value (lowest monthly cost over the highest value, to highest cost over the central value at C${p26:.0f}). "
          f"Even counted only in carbon, a month's slip loses {month_t['ON-avg-traj'][1]/S3:,.1f}–{month_t['ON-marginal-declining'][0]/S3:,.1f} times C1's saving. "
          "This agrees with `initiative_cost.md` §5 (run 5), which found one *day* of delay costs C$1.8–2.9 m against C1's whole carbon value of C$0.49–0.60 m on the current path (C$0.88 m on the superseded C$170).\n")
        # Pre-Q8 (21/10/2026): the current-path-only multiple, previously a hand calculation in Appendix B5.4 ("33 / 0.74 = 45x")
        cv_hi_cur = S3hi * p30 / 1e6
        low_cur = cap * rates[0] / 12 / 1e6 / cv_hi_cur
        high_cur = max(deferred, cap * rates[-1] / 12) / 1e6 / (S3 * p26 / 1e6)
        w(f"**Current path only** (C${p26:.0f}/t in 2026, C${p30:.0f}/t in 2030; superseded path excluded): the largest carbon value is P95 saving × C${p30:.0f} = "
          f"{S3hi:,.0f} t × {p30:.0f} = **C${cv_hi_cur:,.3f} m**, so the multiple runs from C${cap*rates[0]/12/1e6:,.1f} m / {cv_hi_cur:,.3f} = **{low_cur:,.1f}×** "
          f"to C${max(deferred, cap*rates[-1]/12)/1e6:,.1f} m / {S3*p26/1e6:,.3f} = **{high_cur:,.1f}×** (rounded: {low_cur:,.0f}–{high_cur:,.0f}×). "
          "The 30× low end above uses the superseded C$170/t and is therefore the conservative bound.\n")
    else:
        w("[TODO: parameters_run5.yaml not found; dollar cost of delay not computed.]\n")
    w("Caveats: (1) average factors understate what a late baseload unit's output would have displaced in Ontario, where gas is on the margin; (2) the net figure assumes the plant's life is fixed in years, not extended; "
      "(3) deferred output is deferred, not lost: its C$ figure is a cash-flow cost to OPG and ratepayers, not a social loss of that size; (4) the carrying-cost row assumes all capital is already spent, so it is an upper bound for an early slip; "
      "(5) the carbon value is only realised if someone prices it: construction-material emissions are outside Ontario's EPS (analyst inference in run 5, TO VERIFY); (6) all inputs provisional.\n")
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
