# Rubric coverage: R2.3, R3.1, R3.6, R3.7, R2.7, RB.5, R2.4
"""Initiative C1 (LC3 concrete in the DPSC infill and forebay shafts of Darlington Units 2-4):
cost per tonne of CO2e avoided, break-even price premium, carbon value at Canada's carbon price,
and the comparison with the cost of schedule delay.

Reads 03_LCA_Calculations/parameters_run5.yaml (the LC3 saving and volumes are copied there from
results/lca.md, status 'from results'). Section 7 also loads scripts/same_money.py (which reads
parameters_run1.yaml) so the SMR / renewables cost per tonne is never hard-coded. Writes results/initiative_cost.md.
Carbon prices (pre-Q8, 21/10/2026): current federal path C$95 (2026) / C$115 (2030) are the used values;
the superseded 2021 path C$110 / C$170 is shown for comparison only.
Run:  python3 -I 03_LCA_Calculations/scripts/initiative_cost.py

Formulas (per programme of n = 3 units):
  saving per m3          s   = S / V                         [t CO2e/m3]
  extra cost             dC  = pi * c * V * n + Q            [C$]   (pi = price premium as a fraction of GU concrete price c)
  abatement cost         A   = dC / (S * n)                  [C$/t CO2e]   (negative = saves money and carbon)
  break-even premium     pi* = p * s / c   (A = p, Q = 0)    [fraction];  in C$/m3: p * s
  carbon value           CV  = S * n * p                     [C$]
  deferred-output value of one day of delay (Units 2-4): n * MWe * 24 * CF * LCOE_OPG   [C$/day]
  carrying cost of one day of delay (upper bound):        K_U2-4 * r / 365               [C$/day]
"""
from pathlib import Path
import importlib.util
import sys
import numpy as np
import yaml

ROOT = Path(__file__).resolve().parents[1]
RAW = yaml.safe_load((ROOT / "parameters_run5.yaml").read_text())["parameters"]
OUT = ROOT / "results" / "initiative_cost.md"
SEED = 20261021
N_DRAWS = 20000


def num(x):
    if isinstance(x, list):
        return [num(i) for i in x]
    if isinstance(x, str):
        try:
            return float(x)
        except ValueError:
            return x
    return x


P = {k: {f: num(val) for f, val in d.items()} for k, d in RAW.items()}


def v(name, key="value"):
    return P[name][key]


def abate(pi, c, V, S, n, Q):
    return (pi * c * V * n + Q) / (S * n)


def main():
    V, Vlo, Vhi = v("c1_volume_m3_per_unit"), v("c1_volume_m3_per_unit", "low"), v("c1_volume_m3_per_unit", "high")
    S, Slo, Shi = v("c1_saving_t_per_unit"), v("c1_saving_t_per_unit", "low"), v("c1_saving_t_per_unit", "high")
    n = int(v("c1_units"))
    c, clo, chi = v("concrete_price_cad_m3"), v("concrete_price_cad_m3", "low"), v("concrete_price_cad_m3", "high")
    pis = v("premium_scenarios_frac")
    Qs = v("qualification_cost_cad")
    cur = v("carbon_prices_cad")                 # [2026, 2030] current path (used)
    old = v("carbon_prices_superseded_cad")      # [2026, 2030] superseded path (comparison)
    prices = sorted(cur + old)
    p26, p30, p30_old = cur[0], cur[1], old[1]
    basis = {cur[0]: "**2026, current path (used)**", cur[1]: "**2030, current path (used; Units 2-4 concrete placed about 2029-2033)**",
             old[0]: "2026, superseded 2021 path (comparison)", old[1]: "2030, superseded 2021 path (comparison)"}
    s = S / V
    L = []
    w = L.append
    w("Rubric coverage: R2.3, R3.1, R3.6, R3.7, R2.7, RB.5, R2.4")
    w("")
    w("# Initiative C1: cost per tonne CO2e avoided, break-even premium and carbon value (Darlington Units 2-4)")
    w("")
    w("Generated by `03_LCA_Calculations/scripts/initiative_cost.py` from `parameters_run5.yaml`. **PROVISIONAL.** The LC3 saving and volumes are taken as given from `results/lca.md` (lca-analyst, 21/10; their inputs are TO VERIFY). The LC3 price premium and the qualification cost have **no source**: they are scenario values, so the result is framed as a **break-even test** (what premium the carbon price can justify), which does not need them. Reproduce: `python3 -I 03_LCA_Calculations/scripts/initiative_cost.py`.")
    w("")
    w("## 1. Working")
    w("")
    w(f"- Target concrete V = {V:,.0f} m³ per unit ({Vlo:,.0f}-{Vhi:,.0f}); saving S = {S:,.0f} t CO₂e per unit ({Slo:,.0f}-{Shi:,.0f}); n = {n} units -> **{S*n:,.0f} t** for Units 2-4.")
    w(f"- Saving per m³: s = {S:,.0f} / {V:,.0f} = **{s:.3f} t CO₂e/m³** ({s*1000:.0f} kg/m³).")
    w(f"- GU concrete price c = C${c:.0f}/m³ (municipal 32 MPa tender bids C${clo:.0f}-{chi:.0f}, lead). Concrete package for the target structures: {V*n:,.0f} m³ x C${c:.0f} = **C${V*n*c/1e6:.1f} m** for Units 2-4.")
    w(f"- LC3 discount scenario: production cost up to {v('lc3_cost_cut_production'):.0%} lower (LC3 project claim) x binder share {v('binder_share_of_concrete_price'):.0%} of concrete price (assumption) = {v('lc3_cost_cut_production')*v('binder_share_of_concrete_price'):.0%} cheaper concrete.")
    w(f"- Worked example (premium +10%, no qualification cost): A = 0.10 x {c:.0f} x {V:,.0f} x {n} / ({S:,.0f} x {n}) = 0.10 x {c:.0f} / {s:.3f} = **C${abate(0.10, c, V, S, n, 0):.0f}/t**.")
    w("")
    # 2. Scenario matrix
    w("## 2. Abatement cost by premium and qualification-programme cost (C$/t CO₂e, central S, V, c)")
    w("")
    w("| LC3 price premium vs GU | Extra cost, Units 2-4 (no qualification) | " + " | ".join(f"Qualification C${q/1e6:.0f} m" for q in Qs) + " | Range over S, V, c (no qualification) |")
    w("|---|---|" + "---|" * len(Qs) + "---|")
    for pi in pis:
        dc = pi * c * V * n
        cells = " | ".join(f"{abate(pi, c, V, S, n, q):,.0f}" for q in Qs)
        combos = [abate(pi, cc, VV, SS, n, 0) for cc in (clo, chi) for VV in (Vlo, Vhi) for SS in (Slo, Shi)]
        w(f"| {pi:+.0%} | C${dc/1e6:+.2f} m | {cells} | {min(combos):,.0f} to {max(combos):,.0f} |")
    w("")
    w("Negative values mean LC3 saves money as well as carbon. The qualification programme dominates at low premiums: C$1 m spread over 5,190 t adds about C$190/t on its own.")
    w("")
    # 3. Break-even
    w("## 3. Break-even: the premium Canada's carbon price can justify (no qualification cost)")
    w("")
    w("| Carbon price (C$/t) | Basis | Break-even premium (C$/m³) | as % of GU price (C$167 / 229 / 290) | Qualification budget the price covers at 0% premium |")
    w("|---|---|---|---|---|")
    for p in prices:
        w(f"| {p:.0f} | {basis[p]} | {p*s:.1f} | {p*s/clo:.1%} / {p*s/c:.1%} / {p*s/chi:.1%} | C${p*S*n/1e6:.2f} m |")
    w("")
    w(f"Reading: on the current path, LC3 concrete is worth up to **C${p26*s:.1f}–{p30*s:.1f}/m³** more than GU concrete (C${p26:.0f}–{p30:.0f}/t), about **{p26*s/c:.1%}–{p30*s/c:.1%}** of the central commodity price ({p26*s/chi:.1%}–{p30*s/clo:.1%} across the price range). "
      f"If an Ontario LC3 supply costs more than that, or a qualification programme costs more than about C${p26*S*n/1e6:.2f}–{p30*S*n/1e6:.2f} m, the initiative costs more per tonne than the carbon price. "
      f"On the superseded C${p30_old:.0f}/t the break-even would be C${p30_old*s:.1f}/m³ ({p30_old*s/c:.1%}).")
    w("")
    # 4. Carbon value and scale
    w("## 4. Carbon value of the saving, and its size against the project")
    w("")
    K24 = v("dnnp_u24_capital_cad")
    w("| Carbon price (C$/t) | Carbon value, Units 2-4, central (C$ m) | Range over S (C$ m) | Share of Units 2-4 capital (C$13.2 bn) |")
    w("|---|---|---|---|")
    for p in prices:
        w(f"| {p:.0f} | {S*n*p/1e6:.2f} | {Slo*n*p/1e6:.2f}-{Shi*n*p/1e6:.2f} | {S*n*p/K24:.4%} |")
    w("")
    pkg = V * n * c
    w(f"- The whole target-concrete package is about C${pkg/1e6:.1f} m, **{pkg/K24:.3%}** of the Units 2-4 capital. Even a +20% premium (C${0.2*pkg/1e6:.1f} m) is {0.2*pkg/K24:.4%} of it.")
    w("- So **money is not the barrier** to C1. The barriers are qualification (who pays, and does it fit the schedule) and who captures the carbon value: construction-material emissions appear not to be covered by Ontario's EPS, which prices facility emissions [analyst inference, TO VERIFY], so no one is paid the C$/t in section 3 unless a funder or the procurement contract prices it. That is the case for a CGF/BOF milestone condition or an embodied-carbon clause in the Units 2-4 contracts (sections 8.6, 9).")
    w("")
    # 5. Delay
    mwe, cf, lc = 300.0, 0.90, v("opg_dnnp_lcoe_cad")
    day_mwh = n * mwe * 24 * cf
    w("## 5. Cost of one day of delay to Units 2-4, against the initiative")
    w("")
    w(f"- Deferred output: {n} x {mwe:.0f} MW x 24 h x {cf} = {day_mwh:,.0f} MWh/day x C${lc:.0f}/MWh (OPG LCOE lead) = **C${day_mwh*lc/1e6:.1f} m per day** (gross; output is deferred, not lost).")
    for r, lab in ((0.049, "the real rate that reproduces OPG's C$149/MWh in lcoe.md"), (0.07, "run-1 central rate")):
        w(f"- Carrying cost upper bound: C${K24/1e9:.1f} bn x {r:.1%} / 365 = **C${K24*r/365/1e6:.1f} m per day** ({r:.1%} = {lab}; assumes all Units 2-4 capital is already spent).")
    w(f"- Against: the full carbon value of C1 is C${S*n*p26/1e6:.2f}–{S*n*p30/1e6:.2f} m on the current path (C${p26:.0f}–{p30:.0f}/t; C${S*n*p30_old/1e6:.2f} m on the superseded C${p30_old:.0f}); a +10% premium costs C${0.1*pkg/1e6:.2f} m.")
    w(f"- So **one day of delay costs more than the whole initiative's carbon value, in dollars** (C$1.8-2.9 m per day against at most C${S*n*p30/1e6:.2f} m), just as `schedule_value.md` found in tonnes (1.3-14.6 days of delay to a unit cancels its saving). The schedule-neutral condition is therefore the binding implementation requirement, in money as well as carbon: qualify the mix on mock-ups during Unit 1, before the Units 2-4 decision expected in 2028 (lead).")
    w("")
    # 6. Monte Carlo
    rng = np.random.default_rng(SEED)
    Sd = rng.triangular(Slo, S, Shi, N_DRAWS)
    Vd = rng.triangular(Vlo, V, Vhi, N_DRAWS)
    cd = rng.uniform(clo, chi, N_DRAWS)
    pid = rng.uniform(min(pis), max(pis), N_DRAWS)
    Qd = rng.uniform(min(Qs), max(Qs), N_DRAWS)
    A = (pid * cd * Vd * n + Qd) / (Sd * n)
    pct = np.percentile(A, [5, 50, 95])
    w(f"## 6. Monte Carlo ({N_DRAWS:,} draws, seed {SEED})")
    w("")
    w(f"Distributions: S and V triangular (low, central, high); c uniform C${clo:.0f}-{chi:.0f}; premium uniform {min(pis):+.0%} to {max(pis):+.0%}; qualification uniform C$0-{max(Qs)/1e6:.0f} m. The premium and qualification ranges are **assumptions**, so this shows how the answer depends on them, not a forecast.")
    w("")
    w("| Statistic | C$/t CO₂e |")
    w("|---|---|")
    w(f"| P5 | {pct[0]:,.0f} |")
    w(f"| Median | {pct[1]:,.0f} |")
    w(f"| P95 | {pct[2]:,.0f} |")
    for p in prices:
        w(f"| P(cost per t < C${p:.0f}) | {np.mean(A < p):.0%} |")
    w(f"| P(cost per t < 0, saves money) | {np.mean(A < 0):.0%} |")
    w("")
    w("## 7. Comparison for section 9 (same units, C$ or A$ per t CO₂e)")
    w("")
    w(f"- C1 at 0% premium and C$1 m qualification: **C${abate(0, c, V, S, n, 1e6):.0f}/t**; at +10% and C$1 m: **C${abate(0.10, c, V, S, n, 1e6):.0f}/t**.")
    sys.dont_write_bytecode = True
    spec = importlib.util.spec_from_file_location("same_money", ROOT / "scripts" / "same_money.py")
    sm = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(sm)
    bp = sm.base()
    efs = [bp["nsw"], sm.traj(bp)["NEM-T2-slow"](bp["smr_start_aus"]), bp["floor"] + 50]
    smr_c = [bp["lc_smr"] / ((e - bp["ef_smr"]) / 1000) for e in efs]
    vre_c = [bp["lc_vre"] / ((e - bp["ef_vre"]) / 1000) for e in efs]
    w(f"- An SMR at Liddell, gross cost per tonne: **A${min(smr_c):,.0f}-{max(smr_c):,.0f}/t** across the three grid cases in `same_money.md` section 3 (GenCost 2023-24 2030 SMR A${bp['lc_smr']:.0f}/MWh). Firmed renewables: **A${min(vre_c):,.0f}-{max(vre_c):,.0f}/t** on the same basis (A${bp['lc_vre']:.0f}/MWh). Computed here by loading `same_money.py`, so it follows `parameters_run1.yaml`.")
    w("- Not comparable without caution: C1 is a cost per tonne of *embodied* carbon avoided at a plant that is being built anyway. The SMR and renewables figures are gross generation costs per tonne displaced. C1 is a cheap add-on, not an alternative to either.")
    w("")
    w("## 8. Gaps")
    w("- **No source for an LC3 concrete price in Ontario**, or for nuclear-grade SCC prices. The break-even (section 3) is the defensible result until one exists.")
    w("- **No source for the cost of a CSA N287.2 qualification programme.** Ask OPG or a nuclear concrete laboratory (Victor/Leroy).")
    w("- Whether calcined clay is produced at scale in Ontario (TO VERIFY): if imported, both cost and the transport emissions in the LCA change.")
    w("- Canada's industrial carbon benchmark after the 2025 review: if it is lowered or frozen, the break-even falls proportionally.")
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
