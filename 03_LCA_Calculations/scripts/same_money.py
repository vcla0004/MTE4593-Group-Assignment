# Rubric coverage: R3.1, R3.6, R2.3, R2.7, R4.3, RB.6, RB.5
"""Same money: Darlington's budget (or one unit's share) spent on firmed renewables instead.

Reads 03_LCA_Calculations/parameters_run1.yaml only. Writes results/same_money.md.
Run:  python3 -I 03_LCA_Calculations/scripts/same_money.py

Two methods:
  A. Capital-annuity method (uses the real Darlington budget):
       annual capital charge  C_yr = Budget_CAD * FX * CRF(r, n),  CRF = r(1+r)^n / ((1+r)^n - 1)
       capital-only LCOE of the SMR = C_yr / annual MWh                 (cross-check against GenCost)
       firmed-VRE energy the same C_yr buys = C_yr / LCOE_vre            [MWh/yr]
     This is a LOWER bound on the renewables advantage: it ignores the SMR's O&M and fuel
     spending, which would buy still more renewable energy.
  B. LCOE-ratio method (GenCost only, internally consistent in AUD):
       same annual spend buys LCOE_smr / LCOE_vre times the MWh.
  CO2e avoided per A$1m  = (EF_grid - EF_tech) / 1000 [t/MWh] / LCOE [A$/MWh] * 1e6
  Gross cost per tonne   = LCOE / ((EF_grid - EF_tech) / 1000)   (not net of the cost of the displaced supply)
  Cumulative to 2035/2050: SMR from its start year; firmed VRE from vre_first_year, scaled by method-B energy ratio,
  both against the same grid trajectory.
"""
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]
P = yaml.safe_load((ROOT / "parameters_run1.yaml").read_text())["parameters"]
OUT = ROOT / "results" / "same_money.md"


def v(name, key="value"):
    return float(P[name][key])


def lin(y, y0, e0, y1, e1):
    if y <= y0:
        return e0
    if y >= y1:
        return e1
    return e0 + (e1 - e0) * (y - y0) / (y1 - y0)


def crf(r, n):
    return r * (1 + r) ** n / ((1 + r) ** n - 1)


def base():
    return dict(
        net=v("net_mwe"), cf=v("capacity_factor"), units=int(v("units_darlington")),
        budget=v("dnnp_budget_cad"), u1=v("dnnp_unit1_cad") + v("dnnp_common_cad"), fx=v("fx_aud_per_cad"),
        r=v("discount_rate"), n=int(v("annuity_years")),
        lc_smr=v("smr_lcoe_aud"), lc_vre=v("vre_firmed_lcoe_aud"),
        ef_smr=v("smr_lca_g_per_kwh"), ef_vre=v("vre_firmed_lca_g_per_kwh"),
        nsw=v("nsw_scope2_2025"), nem_y0=int(v("nem_traj_start_year")), floor=v("nem_floor_g_per_kwh"),
        x1=int(v("nem_coal_exit_year_stepchange")), x2=int(v("nem_slow_exit_year")),
        ont_y0=int(v("ont_traj_start_year")), ont_avg=v("ont_avg_2024_taf"), ont_2040=v("ont_future_2040"),
        ont_m=v("ont_marginal_taf"), ont_mc=int(v("ont_marginal_converge_year")),
        smr_start_aus=int(v("aus_start_csiro")), smr_start_ont=int(v("ont_unit1_start")),
        vre_start=int(v("vre_first_year")), life=int(v("design_life_yr")),
    )


def traj(p):
    return {
        "NEM-T0-frozen": lambda y: p["nsw"],
        "NEM-T1-StepChange-proxy": lambda y: lin(y, p["nem_y0"], p["nsw"], p["x1"], p["floor"]),
        "NEM-T2-slow": lambda y: lin(y, p["nem_y0"], p["nsw"], p["x2"], p["floor"]),
        "ON-avg-traj": lambda y: lin(y, p["ont_y0"], p["ont_avg"], 2040, p["ont_2040"]),
        "ON-marginal-declining": lambda y: lin(y, p["ont_y0"], p["ont_m"], p["ont_mc"], p["ont_2040"]),
    }


def annual_mwh(p):
    return p["net"] * 8760 * p["cf"]


def cum(p, ef, start, to_year, mwh_yr, ef_tech):
    if to_year < start:
        return 0.0
    return sum(mwh_yr * (ef(y) - ef_tech) / 1000 for y in range(start, to_year + 1))


def method_a(p, budget_cad, n_units):
    c_yr = budget_cad * p["fx"] * crf(p["r"], p["n"])
    smr_mwh = annual_mwh(p) * n_units
    return c_yr, c_yr / smr_mwh, c_yr / p["lc_vre"], smr_mwh


def main():
    p = base()
    T = traj(p)
    L = []
    w = L.append
    w("Rubric coverage: R3.1, R3.6, R2.3, R2.7, R4.3, RB.6, RB.5\n")
    w("# Same money: Darlington's budget on firmed renewables instead\n")
    w("Generated by `03_LCA_Calculations/scripts/same_money.py` from `parameters_run1.yaml`. **PROVISIONAL:** costs, exchange rate and grid factors are TO VERIFY; discount rate, annuity period, renewables start year and the high VRE cost are analyst assumptions.\n")
    w("## 1. Working\n")
    w(f"- Budget: C${p['budget']/1e9:.1f} bn for {p['units']} units (C${p['budget']/p['units']/1e9:.3f} bn per unit, simple share); Unit 1 plus common infrastructure C${p['u1']/1e9:.1f} bn.")
    w(f"- Exchange rate {p['fx']} AUD/CAD (May 2025 lead) → A${p['budget']*p['fx']/1e9:.2f} bn for four units; A${p['budget']*p['fx']/p['units']/1e9:.2f} bn per unit share; A${p['u1']*p['fx']/1e9:.2f} bn Unit 1 + common.")
    w(f"- CRF({p['r']:.0%}, {p['n']} yr) = {crf(p['r'], p['n']):.4f}. Annual output per unit {annual_mwh(p):,.0f} MWh.")
    w(f"- GenCost leads: SMR LCOE A${p['lc_smr']:.0f}/MWh (range {v('smr_lcoe_aud','low'):.0f}–{v('smr_lcoe_aud','high'):.0f}); firmed variable renewables A${p['lc_vre']:.0f}/MWh (range {v('vre_firmed_lcoe_aud','low'):.0f}–{v('vre_firmed_lcoe_aud','high'):.0f}, high end is an assumption).")
    w("- Price-basis caveat: Darlington is a nominal CAD budget (2025 announcement); GenCost is real AUD. Treat method A as an order-of-magnitude cross-check, not a precise conversion.\n")

    w("## 2. Method A: what the Darlington capital would buy\n")
    w("| Budget case | Annual capital charge (A$ m/yr) | SMR capital-only LCOE (A$/MWh) | SMR output (TWh/yr) | Firmed VRE the same charge buys (TWh/yr) | VRE / SMR energy |")
    w("|---|---|---|---|---|---|")
    for label, b, n in [("Four units, C$20.9 bn", p["budget"], p["units"]), ("One unit, simple share", p["budget"] / p["units"], 1), ("Unit 1 + common infrastructure, C$7.7 bn", p["u1"], 1)]:
        c, lc, vre, smr = method_a(p, b, n)
        w(f"| {label} | {c/1e6:,.0f} | {lc:,.0f} | {smr/1e6:,.2f} | {vre/1e6:,.2f} | {vre/smr:,.1f}x |")
    w("")
    w("Capital-only LCOE across discount rates (one unit, simple share), against GenCost's full SMR LCOE range:\n")
    w("| Discount rate | 30-yr annuity | 60-yr annuity |")
    w("|---|---|---|")
    for r in (v("discount_rate", "low"), v("discount_rate"), v("discount_rate", "high")):
        row = []
        for n in (30, 60):
            q = dict(p, r=r, n=n)
            row.append(method_a(q, p["budget"] / p["units"], 1)[1])
        w(f"| {r:.0%} | A${row[0]:,.0f}/MWh | A${row[1]:,.0f}/MWh |")
    w(f"\nGenCost SMR LCOE lead: A${v('smr_lcoe_aud','low'):.0f}–{v('smr_lcoe_aud','high'):.0f}/MWh (includes O&M and fuel). Darlington's capital alone at 7% is consistent with the lower half of that range once O&M and fuel are added [cross-check only; O&M and fuel costs not sourced].\n")

    w("## 3. Method B: LCOE ratio and CO2e avoided per dollar (Liddell / NEM)\n")
    ratio = p["lc_smr"] / p["lc_vre"]
    w(f"Same annual spend buys **{ratio:.1f}x** the MWh as firmed renewables (A${p['lc_smr']:.0f} / A${p['lc_vre']:.0f}).\n")
    w("| Displaced grid intensity (g/kWh) | Case | SMR t CO2e per A$1 m | Firmed VRE t CO2e per A$1 m | SMR gross A$/t | VRE gross A$/t |")
    w("|---|---|---|---|---|---|")
    for ef, lab in [(p["nsw"], "NSW 2025 average (NGA)"), (T["NEM-T2-slow"](p["smr_start_aus"]), f"NEM-T2 in {p['smr_start_aus']}"), (p["floor"] + 50, "post-coal mix + 50 (illustrative)")]:
        s_t = (ef - p["ef_smr"]) / 1000 / p["lc_smr"] * 1e6
        v_t = (ef - p["ef_vre"]) / 1000 / p["lc_vre"] * 1e6
        s_c = p["lc_smr"] / ((ef - p["ef_smr"]) / 1000) if ef > p["ef_smr"] else float("inf")
        v_c = p["lc_vre"] / ((ef - p["ef_vre"]) / 1000) if ef > p["ef_vre"] else float("inf")
        w(f"| {ef:,.0f} | {lab} | {s_t:,.0f} | {v_t:,.0f} | {s_c:,.0f} | {v_c:,.0f} |")
    w("")

    w("## 4. Cumulative CO2e avoided for the same annual spend as one SMR unit\n")
    smr_mwh = annual_mwh(p)
    vre_mwh = smr_mwh * ratio
    spend = smr_mwh * p["lc_smr"]
    w(f"Annual spend = {smr_mwh:,.0f} MWh x A${p['lc_smr']:.0f} = A${spend/1e9:.2f} bn/yr. Firmed VRE bought with it: {vre_mwh/1e6:,.1f} TWh/yr from {p['vre_start']}. SMR: {smr_mwh/1e6:,.2f} TWh/yr from its start year.\n")
    w("| Site | Grid case | SMR start | SMR to 2035 | SMR to 2050 | VRE (from {}) to 2035 | VRE to 2050 | VRE / SMR to 2050 |".format(p["vre_start"]))
    w("|---|---|---|---|---|---|---|---|")
    for site, t, s in [("Liddell", "NEM-T0-frozen", p["smr_start_aus"]), ("Liddell", "NEM-T1-StepChange-proxy", p["smr_start_aus"]),
                       ("Liddell", "NEM-T2-slow", p["smr_start_aus"]), ("Liddell", "NEM-T2-slow", int(v("aus_start_coalition"))),
                       ("Darlington (indicative, GenCost costs)", "ON-avg-traj", p["smr_start_ont"]),
                       ("Darlington (indicative, GenCost costs)", "ON-marginal-declining", p["smr_start_ont"])]:
        ef = T[t]
        a35, a50 = cum(p, ef, s, 2035, smr_mwh, p["ef_smr"]), cum(p, ef, s, 2050, smr_mwh, p["ef_smr"])
        b35, b50 = cum(p, ef, p["vre_start"], 2035, vre_mwh, p["ef_vre"]), cum(p, ef, p["vre_start"], 2050, vre_mwh, p["ef_vre"])
        rr = f"{b50/a50:,.1f}x" if a50 > 0 else "SMR ≤ 0"
        w(f"| {site} | {t} | {s} | {a35/1e6:,.2f} Mt | {a50/1e6:,.2f} Mt | {b35/1e6:,.2f} Mt | {b50/1e6:,.2f} Mt | {rr} |")
    w("")
    w("Caveats: (1) adding about {:.0f} TWh/yr of firmed renewables would itself change the NEM trajectory; the comparison is at the margin of the stated trajectory. (2) Firmed-VRE LCOE rises with the renewable share; GenCost's integration costs cover this only up to its modelled shares. (3) Renewable assets last about 25–30 years [TO VERIFY, GenCost], so to 2050 no replacement is needed, but whole-life comparisons would need one. (4) Ontario rows use Australian costs and are indicative only (Ontario-specific costs are STRETCH in the plan).\n".format(vre_mwh / 1e6))

    w("## 5. Sensitivity (Liddell, NEM-T2-slow, SMR from {}; VRE/SMR CO2e ratio to 2050)\n".format(p["smr_start_aus"]))
    w("| Change | Energy ratio (B) | VRE / SMR CO2e to 2050 |")
    w("|---|---|---|")

    def run(**kw):
        q = dict(p, **kw)
        TT = traj(q)
        rt = q["lc_smr"] / q["lc_vre"]
        sm = annual_mwh(q)
        a = cum(q, TT["NEM-T2-slow"], q["smr_start_aus"], 2050, sm, q["ef_smr"])
        b = cum(q, TT["NEM-T2-slow"], q["vre_start"], 2050, sm * rt, q["ef_vre"])
        return rt, b / a if a > 0 else float("nan")

    for lab, kw in [("Central", {}), ("SMR LCOE low (387)", {"lc_smr": v("smr_lcoe_aud", "low")}), ("SMR LCOE high (641)", {"lc_smr": v("smr_lcoe_aud", "high")}),
                    ("SMR LCOE 198 (alt. lead)", {"lc_smr": v("smr_lcoe_low_alt_aud")}),
                    ("VRE LCOE low (91)", {"lc_vre": v("vre_firmed_lcoe_aud", "low")}), ("VRE LCOE high (153, assumption)", {"lc_vre": v("vre_firmed_lcoe_aud", "high")}),
                    ("Worst case for VRE (SMR 198, VRE 153)", {"lc_smr": v("smr_lcoe_low_alt_aud"), "lc_vre": v("vre_firmed_lcoe_aud", "high")}),
                    ("SMR starts 2035", {"smr_start_aus": int(v("aus_start_coalition"))}), ("VRE starts 2030", {"vre_start": int(v("vre_first_year", "high"))}),
                    ("VRE life-cycle 83 g/kWh", {"ef_vre": v("vre_firmed_lca_g_per_kwh", "high")})]:
        rt, cr = run(**kw)
        w(f"| {lab} | {rt:,.1f}x | {cr:,.1f}x |")
    w("")
    w("Note on the Ontario average row: once Ontario's average falls below the placeholder firmed-VRE life-cycle value (30 g/kWh), extra renewables 'add' emissions against that average, and the SMR's lower life-cycle value wins. That is a real property of a near-clean grid, but it hangs on two placeholders (the VRE life-cycle value and the IESO 2040 lead) and on using the average, not the marginal, factor.\n")
    w("Reading: in every tested Liddell case the same money spent on firmed renewables avoids more CO2e by 2050 than one SMR, because it is cheaper per MWh and starts about a decade earlier. The SMR's case therefore rests on non-cost objectives (firmness, land, system security, a hedge if renewables and transmission are delayed), which belong in the MCDA (§9), not on carbon per dollar.\n")
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
