# Rubric coverage: R3.2, R3.4, R3.8, R2.4, RB.5
"""Licensing durations (Darlington) and Senate arithmetic for repealing Australia's federal bans.

Reads 03_LCA_Calculations/parameters_run2.yaml only. Writes results/law_timelines.csv.
Run:  python3 -I 03_LCA_Calculations/scripts/law_timelines.py

Every input is status "TO VERIFY" (see the YAML header). Outputs inherit that status.

Method:
  months between two dates = (days between them) / (365.25 / 12)
  Senate majority to pass a bill = floor(total / 2) + 1  (a tied vote fails, Constitution s23 [TO VERIFY wording])
  shortfall = majority - pro-repeal bloc (upper bound, see note in YAML)
  Sensitivity: the LTC duration is also given with the application date moved to the
  first and last day of October 2022, because CNSC gives only the month.
"""
from datetime import date
from pathlib import Path
import csv
import yaml

ROOT = Path(__file__).resolve().parents[1]
P = yaml.safe_load((ROOT / "parameters_run2.yaml").read_text())["parameters"]
OUT = ROOT / "results" / "law_timelines.csv"
MONTH = 365.25 / 12


def d(name):
    val = P[name]["value"]
    if isinstance(val, date):
        return val
    s = str(val)
    if len(s) == 7:  # year-month: use the first of the month
        s += "-01"
    return date.fromisoformat(s)


def months(a, b):
    return (b - a).days / MONTH


rows = []

ltc_app, ltc_dec = d("dnnp_ltc_application"), d("dnnp_ltc_decision")
rows.append(("ltc_application_to_decision_months", round(months(ltc_app, ltc_dec), 1), "months",
             "dnnp_ltc_application, dnnp_ltc_decision"))
rows.append(("ltc_application_to_decision_years", round(months(ltc_app, ltc_dec) / 12, 2), "years",
             "same"))
for label, day in (("low", date(2022, 10, 31)), ("high", date(2022, 10, 1))):
    rows.append((f"ltc_months_sensitivity_{label}", round(months(day, ltc_dec), 1), "months",
                 f"application assumed {day.isoformat()}"))
rows.append(("ltc_vs_cnsc_expected_months", round(months(ltc_app, ltc_dec) - P["cnsc_expected_ltc_months"]["value"], 1),
             "months (negative = faster than CNSC's expected time)", "cnsc_expected_ltc_months"))
rows.append(("hearing_part2_to_decision_months", round(months(d("dnnp_ltc_hearing_part2_start"), ltc_dec), 1),
             "months", "dnnp_ltc_hearing_part2_start"))
rows.append(("ea_start_to_ltc_decision_years", round(months(d("dnnp_ea_start"), ltc_dec) / 12, 1), "years",
             "dnnp_ea_start (elapsed, not active review)"))
rows.append(("ltc_validity_remaining_from_decision_years", round(months(ltc_dec, d("dnnp_ltc_expiry")) / 12, 1),
             "years", "dnnp_ltc_expiry"))
rows.append(("ltc_validity_remaining_from_2026_10_20_years", round(months(date(2026, 10, 20), d("dnnp_ltc_expiry")) / 12, 1),
             "years", "report date 20/10/2026"))
rows.append(("rhp1_lifted_after_ltc_months", round(months(ltc_dec, d("dnnp_rhp1_lifted")), 1), "months",
             "dnnp_rhp1_lifted"))

# Senate arithmetic
total = P["senate_total_seats"]["value"]
parts = sum(P[k]["value"] for k in ("senate_alp", "senate_coalition", "senate_greens",
                                     "senate_one_nation", "senate_other_crossbench"))
assert parts == total, f"Senate parts {parts} != total {total}"
majority = total // 2 + 1
bloc = P["senate_pro_repeal_max"]["value"]
rows.append(("senate_majority_needed", majority, "seats", "senate_total_seats"))
rows.append(("senate_pro_repeal_bloc_max", bloc, "seats", "assumes Coalition + One Nation + Babet all vote yes"))
rows.append(("senate_shortfall", majority - bloc, "seats", "majority - bloc"))
rest = P["senate_other_crossbench"]["value"] - 1  # crossbench excluding Babet
rows.append(("senate_bloc_plus_all_other_crossbench", bloc + rest, "seats",
             "even if Lambie, Payman, Pocock and Thorpe all voted yes"))
rows.append(("senate_passes_without_alp_or_greens", int(bloc + rest >= majority), "1 = yes, 0 = no", "test"))
rows.append(("senate_passes_with_greens_only", int(bloc + P["senate_greens"]["value"] >= majority), "1 = yes, 0 = no",
             "test (Greens oppose: policy, not arithmetic)"))

OUT.parent.mkdir(parents=True, exist_ok=True)
with OUT.open("w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["# Rubric coverage: R3.2, R3.4, R3.8, RB.5. Generated by scripts/law_timelines.py. Inputs TO VERIFY."])
    w.writerow(["quantity", "value", "unit", "inputs / note"])
    w.writerows(rows)

for r in rows:
    print(f"{r[0]:48s} {r[1]!s:>8}  {r[2]}")
