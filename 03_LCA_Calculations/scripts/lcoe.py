        ("Capex x0.85 / x1.75 (CFPP-sized overrun)", dict(b, capex_mult=v("capex_low_factor")), dict(b, capex_mult=v("capex_high_factor"))),
        ("Economic life 60 / 30 yr", dict(b, n=60), dict(b, n=30)),
        ("Capacity factor 0.95 / 0.80", dict(b, cf=P["capacity_factor"]["high"]), dict(b, cf=P["capacity_factor"]["low"])),
        ("Opex fleet low / single-unit high", dict(b, opex_usd=v("opex_fleet_usd_mwh")), dict(b, opex_usd=v("opex_single_unit_usd_mwh"))),
        ("IDC share stripped 0.25 / 0.0", dict(b, s_idc=P["idc_share_of_budget"]["high"]), dict(b, s_idc=P["idc_share_of_budget"]["low"])),
        ("Build period 4 / 7 yr", dict(b, t=P["build_years"]["low"]), dict(b, t=P["build_years"]["high"])),
