    w("")
    # ---------------- 1. Working
    E = energy(b)
    w("## 1. Working")
    w("")
    w(f"- Capital: C${b['budget']/1e9:.1f} bn for {b['units']} x {b['mwe']} MWe = {b['units']*b['mwe']:,} MWe, i.e. **C${b['budget']/(b['units']*b['mwe']*1000):,.0f}/kW** all-in (includes OPG's interest, escalation and contingency).")
    w(f"- Output: {b['units']} x {b['mwe']} MW x 8,760 h x {b['cf']} = **{E/1e6:.2f} TWh/yr** ({E:,.0f} MWh).")
    w(f"- Opex (central, vendor-advertised BWRX-300): fixed O&M US${v('fom_vendor_usd_mwh')} + variable O&M US${v('vom_usd_mwh')} + fuel US${v('fuel_vendor_usd_mwh')} = US${b['opex_usd']:.2f}/MWh x {b['fx']} CAD/USD = **C${b['opex_usd']*b['fx']:.1f}/MWh**.")
    w(f"- Capital case A: K = budget. Case B: K = budget x (1 - {b['s_idc']}) x F_IDC(r, {b['t']} yr). F_IDC = " + ", ".join(f"{f_idc(r, int(b['t'])):.3f} at {r:.0%}" for r in rates) + ".")
    w("- CRF(r, n) = r(1+r)^n / ((1+r)^n - 1): " + "; ".join(f"{r:.0%}: {crf(r,60):.4f} (60 yr), {crf(r,30):.4f} (30 yr)" for r in rates) + ".")
    w(f"- Worked example (case B, 7%, 60 yr): K = 20.9e9 x {1-b['s_idc']:.2f} x {f_idc(0.07, int(b['t'])):.3f} = C${capital(b)/1e9:.2f} bn; capital charge = K x {crf(0.07,60):.4f} / {E:,.0f} MWh = C${lcoe(b)[1]:.1f}/MWh; plus opex C${lcoe(b)[2]:.1f} = **C${lcoe(b)[0]:.0f}/MWh** (A${lcoe(b)[0]*aud:.0f}/MWh at {aud} AUD/CAD).")
