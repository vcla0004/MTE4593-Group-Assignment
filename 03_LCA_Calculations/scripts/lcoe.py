# Rubric coverage: R3.1, R2.3, R2.7, RB.6, RB.5, R2.4
"""Own LCOE for the Darlington New Nuclear Project (4 x BWRX-300), with discount-rate sensitivity,
benchmarked against OPG's reported LCOE and CSIRO GenCost; plus the NuScale/UAMPS cost-risk arithmetic
and US SMR developer valuation ratios.

Reads 03_LCA_Calculations/parameters_run5.yaml only. Writes results/lcoe.md.
Run:  python3 -I 03_LCA_Calculations/scripts/lcoe.py

Method (simple levelised cost, real terms, constant output from commercial operation):
  CRF(r, n)       = r(1+r)^n / ((1+r)^n - 1)
  Capital case A  ("as budgeted"):  K = Budget                      (budget already includes OPG's IDC)
  Capital case B  ("IDC re-based"): K = Budget * (1 - s_IDC) * F_IDC(r, T)
                    F_IDC(r, T) = (1/T) * sum_{k=1..T} (1+r)^(T - k + 0.5)   (uniform spend, mid-year)
                    i.e. strip an assumed IDC share, then re-add IDC at the test discount rate.
  Annual output   E = units * MWe * 8760 * CF     [MWh/yr]
  LCOE            = K * CRF(r, n) / E + (fixed O&M + variable O&M + fuel) * FX
Case B is the one that makes discount-rate sensitivity meaningful (case A charges OPG's financing and then
discounts again). Decommissioning and waste fees are not separately included (they sit inside the opex
benchmarks only to the extent the sources include them) - stated as a limitation.
"""
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]
P = yaml.safe_load((ROOT / "parameters_run5.yaml").read_text())["parameters"]
OUT = ROOT / "results" / "lcoe.md"


def num(x):
    """PyYAML reads '20.9e9' as a string; coerce numeric strings (and lists of them) to float."""
    if isinstance(x, list):
        return [num(i) for i in x]
    if isinstance(x, str):
        try:
            return float(x)
        except ValueError:
            return x
    return x


P = {k: {f: num(val) for f, val in d.items()} for k, d in P.items()}


def v(name, key="value"):
    return P[name][key]


def crf(r, n):
    return r * (1 + r) ** n / ((1 + r) ** n - 1)


def f_idc(r, t):
    return sum((1 + r) ** (t - k + 0.5) for k in range(1, t + 1)) / t


def base():
    fx = v("fx_cad_per_usd")
    return dict(
        budget=v("dnnp_budget_cad"), units=v("units"), mwe=v("net_mwe"), cf=v("capacity_factor"),
        n=v("econ_life_yr"), s_idc=v("idc_share_of_budget"), t=v("build_years"), capex_mult=1.0,
        opex_usd=v("fom_vendor_usd_mwh") + v("vom_usd_mwh") + v("fuel_vendor_usd_mwh"), fx=fx, r=0.07,
        case="B",
    )


def capital(p):
    k = p["budget"] * p["capex_mult"]
    if p["case"] == "A":
        return k
    return k * (1 - p["s_idc"]) * f_idc(p["r"], int(p["t"]))


def energy(p):
    return p["units"] * p["mwe"] * 8760 * p["cf"]


def lcoe(p):
    cap = capital(p) * crf(p["r"], int(p["n"])) / energy(p)
    opx = p["opex_usd"] * p["fx"]
    return cap + opx, cap, opx


def solve_r(target, p):
    lo, hi = 0.0001, 0.30
    for _ in range(100):
        mid = (lo + hi) / 2
        q = dict(p, r=mid)
        if lcoe(q)[0] > target:
            hi = mid
        else:
            lo = mid
    return (lo + hi) / 2


def fmt(x, d=0):
    return f"{x:,.{d}f}"


