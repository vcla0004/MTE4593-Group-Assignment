    best = lcoe(dict(b, r=0.03, capex_mult=v("capex_low_factor"), cf=0.95, opex_usd=v("opex_fleet_usd_mwh"), n=60, s_idc=0.25, mwe=315))[0]
    w("")
    w(f"Combined bounds (all low / all high together, not a probability interval): **C${best:.0f}-{worst:.0f}/MWh** (A${best*aud:.0f}-{worst*aud:.0f}).")
    w("")
